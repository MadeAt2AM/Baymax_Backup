#!/usr/bin/env bash
#
# /srv/scripts/custom-domain-sync.sh
# Auto-sync verified custom domains from the SYNTRA DB into Caddy site blocks.
#
# Context:
#   When a platform admin sets a company's `customDomain` and the DNS check
#   passes, the DB row flips to domain_status='verified'. Caddy needs a
#   host block for that domain to terminate TLS + reverse-proxy it.
#   This script generates those blocks automatically so we don't have to
#   SSH in and edit /srv/caddy/sites/syntra.caddy by hand for every
#   new tenant.
#
# What it does:
#   1. Reads POSTGRES_PASSWORD from /srv/secrets/syntra.env
#   2. Queries the syntra DB for companies where domain_status='verified'
#      and custom_domain IS NOT NULL
#   3. Writes /srv/caddy/sites/syntra.auto.caddy with one block per domain:
#        <domain> {
#            reverse_proxy syntra-web:80
#        }
#   4. Only reloads Caddy if the generated file actually changed
#      (idempotent — safe to run every minute)
#
# Requirements:
#   - psql client available on the VPS (or reachable via the postgres container)
#   - Caddy container named `caddy`
#   - The main Caddyfile already has:  import /etc/caddy/sites/*.caddy
#     (it does — that's how per-project sites are loaded)
#
# Install:
#   chmod +x /srv/scripts/custom-domain-sync.sh
#   Add to root crontab:  */2 * * * *  /srv/scripts/custom-domain-sync.sh
#
# Logging: writes to syslog with tag custom-domain-sync
#
set -euo pipefail

SECRETS_FILE="/srv/secrets/syntra.env"
AUTO_FILE="/srv/caddy/sites/syntra.auto.caddy"
CADDY_CONTAINER="caddy"
TAG="custom-domain-sync"

# ---- 1. Load DB creds from the secrets file ----
if [[ ! -f "$SECRETS_FILE" ]]; then
  logger -t "$TAG" "ERROR: secrets file $SECRETS_FILE not found"
  exit 1
fi
# Source only the vars we need (safe-ish: file is root-owned 600)
POSTGRES_PASSWORD="$(grep -i '^POSTGRES_PASSWORD=' "$SECRETS_FILE" | head -1 | cut -d= -f2-)"
DB_USER="syntra"
DB_NAME="syntra"
# Postgres runs in a container; reach it over the docker network by service name.
PGHOST="syntra_postgres"

if [[ -z "$POSTGRES_PASSWORD" ]]; then
  logger -t "$TAG" "ERROR: POSTGRES_PASSWORD not found in $SECRETS_FILE"
  exit 1
fi

# ---- 2. Query verified domains ----
QUERY="SELECT custom_domain FROM companies WHERE domain_status='verified' AND custom_domain IS NOT NULL ORDER BY custom_domain;"
DOMAINS=$(PGPASSWORD="$POSTGRES_PASSWORD" psql -h "$PGHOST" -U "$DB_USER" -d "$DB_NAME" \
  -t -A -c "$QUERY" 2>/dev/null)

# ---- 3. Build the auto file ----
TMP="$(mktemp)"
{
  echo "# AUTO-GENERATED by $0 — DO NOT EDIT BY HAND"
  echo "# Verified tenant custom domains. Reloaded by Caddy on change."
  echo
  while IFS= read -r d; do
    [[ -z "$d" ]] && continue
    echo "$d {"
    echo "    reverse_proxy syntra-web:80"
    echo "}"
    echo
  done <<< "$DOMAINS"
} > "$TMP"

# ---- 4. Diff + conditional reload ----
if cmp -s "$TMP" "$AUTO_FILE" 2>/dev/null; then
  rm -f "$TMP"
  logger -t "$TAG" "No change in verified domains — skipping reload"
  exit 0
fi

mv "$TMP" "$AUTO_FILE"
logger -t "$TAG" "Domain set changed — reloading Caddy"

if docker exec "$CADDY_CONTAINER" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile 2>&1; then
  logger -t "$TAG" "Caddy reloaded OK"
else
  logger -t "$TAG" "ERROR: caddy reload failed"
  exit 1
fi